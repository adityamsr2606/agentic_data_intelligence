from pathlib import Path

from pydantic import Field
from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    """
    Central configuration for the application.

    Values are read from the .env file so that configuration does
    not get scattered across different modules.
    """

    # Local Agentic AI
    ollama_model: str = "qwen3:4b"
    ollama_host: str = "http://localhost:11434"

    # Agent behaviour
    max_agent_rounds: int = Field(
        default=4,
        ge=1,
        le=10,
    )

    max_sample_rows: int = Field(
        default=25,
        ge=5,
        le=200,
    )

    max_document_chars: int = Field(
        default=20000,
        ge=1000,
    )

    min_rule_confidence: float = Field(
        default=0.80,
        ge=0.0,
        le=1.0,
    )

    min_mapping_confidence: float = Field(
        default=0.75,
        ge=0.0,
        le=1.0,
    )

    # Database
    database_enabled: bool = False
    database_url: str = ""
    database_schema: str = "public"

    # Reporting
    report_directory: Path = Path("reports")
    generate_html_report: bool = True

    # Application
    app_env: str = "development"
    log_level: str = "INFO"

    model_config = SettingsConfigDict(
        env_file=".env",
        env_file_encoding="utf-8",
        case_sensitive=False,
        extra="ignore",
    )


settings = Settings()


def ensure_runtime_directories() -> None:
    """
    Create directories that are generated by the application.
    """

    settings.report_directory.mkdir(
        parents=True,
        exist_ok=True,
    )